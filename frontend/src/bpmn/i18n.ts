export function translate(template: string, replacements?: Record<string, string>): string {
  if (!template) {
    return template
  }
  const translated = translations[template] || template
  if (!replacements) {
    return translated
  }
  return translated.replace(/{([^}]+)}/g, (_, key: string) => replacements[key] ?? `{${key}}`)
}

export const customTranslateModule = {
  translate: ['value', translate]
}
